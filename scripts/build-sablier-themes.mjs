// Writes sablier-themes/p7y.html and leander.html (old leander-* sandboxes use that name)
// from ui/waiting.css, ui/embers.js and ui/waiting.js. Sablier serves the page on the
// sandbox's own host, where Purgatory's /assets are not reachable, so everything is inlined.
// Run after changing any of those files:  node scripts/build-sablier-themes.mjs
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const read = f => fs.readFileSync(path.join(root, 'ui', f), 'utf8').replace(/\r\n/g, '\n').trim()
const flame = `<svg viewBox="0 0 64 64" aria-hidden="true"><defs><linearGradient id="p7y-wf" x1="0" y1="1" x2="0" y2="0"><stop offset="0" stop-color="#ff5a00"/><stop offset=".6" stop-color="#ff9a2e"/><stop offset="1" stop-color="#ffe0a0"/></linearGradient></defs><path fill="url(#p7y-wf)" d="M32 4c5 13 18 19 18 36a18 18 0 0 1-36 0c0-11 7-15 9-24 4 5 6 10 5 16 6-7 8-15 4-28Z"/><path fill="#fff1c9" d="M32 30c3 5 7 7 7 13a7 7 0 0 1-14 0c0-4 3-6 4-9 1 2 2 4 2 6 2-3 2-6 1-10Z"/></svg>`

const theme = `<!DOCTYPE html>
<!-- Generated by scripts/build-sablier-themes.mjs from ui/waiting.css, ui/embers.js, ui/waiting.js: edit those, then re-run it. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<noscript><meta http-equiv="refresh" content="{{ .RefreshFrequency }}"></noscript>
<title>Waking up — {{ .DisplayName }}</title>
<style>
${read('waiting.css')}
</style>
</head>
<body>
<canvas data-embers aria-hidden="true" style="position:fixed;inset:0;width:100%;height:100%;pointer-events:none"></canvas>
<div class="heat"></div>
<div class="wrap"><div class="card" data-p7y-waiting data-refresh="{{ .RefreshFrequency }}">
  <div class="coal" data-coal><div class="core"></div>${flame}</div>
  <h1>Sandbox is waking up</h1>
  <div class="name">{{ .DisplayName }}</div>
  <ul data-states>
    {{- range $i, $instance := .InstanceStates }}
    <li>
      <span>{{ $instance.Name }}</span>
      {{- if $instance.Error }}
      {{- /* A container stopped by sleep exits with a code (frps 2, socat 137): that is "starting", not an error */}}
      {{- $e := printf "%v" $instance.Error }}
      {{- if and (ge (len $e) 26) (eq (slice $e 0 26) "container exited with code") }}
      <span data-state="starting"><span class="dot starting"></span>starting</span>
      {{- else }}
      <span class="error" data-state="error"><span class="dot error"></span>{{ $e }}</span>
      {{- end }}
      {{- else if eq $instance.Status "ready" }}
      <span data-state="ready"><span class="dot ready"></span>ready</span>
      {{- else }}
      <span data-state="starting"><span class="dot starting"></span>starting</span>
      {{- end }}
    </li>
    {{- end }}
  </ul>
  <div class="hint">This page updates by itself. The sandbox sleeps again after {{ .SessionDuration }} without traffic.</div>
</div></div>
<script>
${read('embers.js')}
</script>
<script>
${read('waiting.js')}
</script>
</body>
</html>
`

for (const name of ['p7y.html', 'leander.html']) fs.writeFileSync(path.join(root, 'sablier-themes', name), theme)
console.log('wrote sablier-themes/p7y.html and leander.html')
